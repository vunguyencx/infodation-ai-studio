// Static server + document upload API for the admin page.
//   node serve.js [port]
// Uploads are enabled only when ADMIN_TOKEN is set, e.g.:
//   ADMIN_TOKEN=change-me node serve.js            (bash)
//   $env:ADMIN_TOKEN="change-me"; node serve.js     (PowerShell)
const http = require('http'), fs = require('fs'), path = require('path'), crypto = require('crypto');
const root = __dirname, port = Number(process.argv[2]) || 5173;
const TOKEN = process.env.ADMIN_TOKEN || '';
const MAX = 25 * 1024 * 1024;
const DOC_KEYS = ['company-profile', 'intellicad', 'document-ai', 'voice-bot'];
const LANGS = ['en', 'vi', 'nl'];
const DOCS_DIR = path.join(root, 'assets', 'docs');
const MANIFEST = path.join(DOCS_DIR, 'docs.json');
const DOCS_JS = path.join(root, 'assets', 'js', 'docs.js');
const types = { '.html': 'text/html; charset=utf-8', '.css': 'text/css', '.js': 'text/javascript', '.json': 'application/json', '.svg': 'image/svg+xml', '.jpg': 'image/jpeg', '.png': 'image/png', '.pdf': 'application/pdf', '.woff2': 'font/woff2' };

function readManifest() {
  try { return JSON.parse(fs.readFileSync(MANIFEST, 'utf8')); } catch (e) { return {}; }
}
function writeManifest(m) {
  fs.mkdirSync(DOCS_DIR, { recursive: true });
  fs.writeFileSync(MANIFEST, JSON.stringify(m, null, 2));
  // the site loads this as a plain script so it also works from file:// and static hosting
  fs.writeFileSync(DOCS_JS, '/* Generated by serve.js from assets/docs/docs.json — do not edit by hand. */\nwindow.IFD_DOCS = ' + JSON.stringify(m, null, 2) + ';\n');
}
function json(res, code, body) {
  res.writeHead(code, { 'content-type': 'application/json', 'cache-control': 'no-store' });
  res.end(JSON.stringify(body));
}
function authorised(req) {
  if (!TOKEN) return false;
  const got = Buffer.from(String(req.headers['authorization'] || '').replace(/^Bearer\s+/i, ''));
  const want = Buffer.from(TOKEN);
  return got.length === want.length && crypto.timingSafeEqual(got, want);
}

function api(req, res, p) {
  if (p === '/api/status' && req.method === 'GET') return json(res, 200, { uploads: !!TOKEN, docs: readManifest() });
  const m = p.match(/^\/api\/docs\/([a-z-]+)\/([a-z]{2})$/);
  if (!m || DOC_KEYS.indexOf(m[1]) === -1 || LANGS.indexOf(m[2]) === -1) return json(res, 404, { error: 'not_found' });
  if (!TOKEN) return json(res, 403, { error: 'uploads_disabled' });
  if (!authorised(req)) return json(res, 401, { error: 'bad_key' });
  const key = m[1], lang = m[2], file = path.join(DOCS_DIR, key, lang + '.pdf');

  if (req.method === 'DELETE') {
    const man = readManifest();
    try { fs.unlinkSync(file); } catch (e) { /* already gone */ }
    if (man[key]) { delete man[key][lang]; if (!Object.keys(man[key]).length) delete man[key]; }
    writeManifest(man);
    return json(res, 200, { ok: true, docs: man });
  }
  if (req.method !== 'PUT') return json(res, 405, { error: 'method' });

  const chunks = []; let size = 0, aborted = false;
  req.on('data', (c) => {
    size += c.length;
    if (size > MAX) { aborted = true; json(res, 413, { error: 'too_large' }); req.destroy(); return; }
    chunks.push(c);
  });
  req.on('end', () => {
    if (aborted) return;
    const buf = Buffer.concat(chunks);
    if (buf.slice(0, 5).toString('latin1') !== '%PDF-') return json(res, 415, { error: 'not_pdf' });
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, buf);
    const man = readManifest();
    const name = decodeURIComponent(String(req.headers['x-filename'] || lang + '.pdf')).replace(/[^\w.\- ()À-ỹ]/g, '_').slice(0, 120);
    man[key] = man[key] || {};
    man[key][lang] = { path: 'assets/docs/' + key + '/' + lang + '.pdf', name: name, size: buf.length, updated: new Date().toISOString() };
    writeManifest(man);
    json(res, 200, { ok: true, docs: man });
  });
}

http.createServer((req, res) => {
  let p = decodeURIComponent(new URL(req.url, 'http://x').pathname);
  if (p.startsWith('/api/')) return api(req, res, p);
  if (p.endsWith('/')) p += 'index.html';
  const file = path.join(root, p);
  if (!file.startsWith(root)) { res.writeHead(403); return res.end(); }
  fs.readFile(file, (err, buf) => {
    if (err) { res.writeHead(404, { 'content-type': 'text/plain' }); return res.end('Not found'); }
    res.writeHead(200, { 'content-type': types[path.extname(file)] || 'application/octet-stream', 'cache-control': 'no-store' });
    res.end(buf);
  });
}).listen(port, () => console.log('http://localhost:' + port + (TOKEN ? '  (document uploads enabled)' : '  (uploads disabled: set ADMIN_TOKEN)')));
