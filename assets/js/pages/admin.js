/* Admin settings: pick the color combo + default language, preview live, export config.js to publish. */
(function () {
  var I = window.IFD_I18N, U = window.IFD_UI, P = window.IFD_PALETTES, TH = window.IFD_THEME, C = window.IFD_CONFIG;
  var t = I.t, esc = U.esc;
  var $ = function (id) { return document.getElementById(id); };
  var LANG_KEY = 'ifd.admin.defaultLang';
  var LANG_NAMES = { en: 'English', vi: 'Tiếng Việt', nl: 'Nederlands' };

  function getLang() { try { return localStorage.getItem(LANG_KEY) || C.defaultLang; } catch (e) { return C.defaultLang; } }
  function setLang(l) { try { localStorage.setItem(LANG_KEY, l); } catch (e) { /* ignore */ } }

  function toast(msg) {
    var el = $('toast'); el.textContent = msg; el.classList.add('on');
    clearTimeout(toast._t); toast._t = setTimeout(function () { el.classList.remove('on'); }, 1800);
  }

  function config() {
    return '/* Site-wide defaults — what every visitor sees.\n * Generated by admin.html → "Export config.js". Replace this file on the server to publish.\n */\n' +
      'window.IFD_CONFIG = {\n' +
      "  palette: '" + TH.current() + "',\n" +
      "  defaultLang: '" + getLang() + "',\n" +
      "  languages: ['en', 'vi', 'nl']\n};\n";
  }

  function render() {
    var cur = TH.current(), lang = I.lang, roles = t('admin.roles');
    $('palettes').innerHTML = P.list.map(function (p) {
      var v = P.resolve(p), on = p.id === cur, keys = ['ink', 'accent', 'pop', 'note', 'live'];
      return '<button type="button" class="pal" role="radio" aria-checked="' + on + '" data-pal="' + p.id + '" data-asm="piece" data-tilt="5">' +
        '<div style="display:flex;justify-content:space-between;align-items:center;gap:10px"><div style="display:flex;flex-direction:column;gap:2px">' +
        '<b style="font-family:var(--f-display);font-size:20px">' + esc(p.name[lang] || p.name.en) + '</b>' +
        '<span style="font-size:13px;color:var(--text-3)">' + esc(p.note[lang] || p.note.en) + '</span></div>' +
        (on ? '<span class="pill-live" style="font-size:12px;font-weight:700">' + t('admin.active') + '</span>' : '<span style="font-size:13px;font-weight:700;text-decoration:underline">' + t('admin.apply') + '</span>') + '</div>' +
        '<div class="sw">' + keys.map(function (k) { return '<i style="background:' + v[k] + (k === 'pop' ? ';box-shadow:inset 0 0 0 1px rgba(0,0,0,.06)' : '') + '"></i>'; }).join('') + '</div>' +
        '<div class="sw-l">' + keys.map(function (k, i) { return '<span>' + roles[i] + '<br>' + v[k] + '</span>'; }).join('') + '</div>' +
        '<div class="mini" style="background:' + v.bg + ';color:' + v.ink + '">' +
        '<b>' + I.plain(t('admin.sample')).replace(/(\S+)\.$/, '<span style="background:' + v.pop + ';padding:0 6px;border-radius:8px">$1.</span>') + '</b>' +
        '<div class="r"><span class="p" style="background:' + v.accent + ';color:' + v.ink + '">' + t('admin.sampleBtn') + ' →</span>' +
        '<span class="p" style="background:' + v.live + ';color:' + v.ink + '">01</span>' +
        '<span style="font-family:var(--f-display);font-weight:800;color:' + v.note + '">07</span>' +
        '<span class="p" style="background:' + v.ink + ';color:#fff">AI</span>' +
        '<span class="p" style="background:' + v.inkDeep + ';color:' + v.onInk1 + '">footer</span></div></div>' +
        '</button>';
    }).join('');
    var dl = getLang();
    $('langs').innerHTML = I.langs.map(function (l) {
      return '<button type="button" role="radio" aria-checked="' + (l === dl) + '" aria-pressed="' + (l === dl) + '" data-deflang="' + l + '">' + LANG_NAMES[l] + ' <span>' + l.toUpperCase() + '</span></button>';
    }).join('');
    $('cfg').textContent = config();
  }

  document.addEventListener('click', function (e) {
    var p = e.target.closest('[data-pal]');
    if (p) { TH.save(p.getAttribute('data-pal')); render(); window.IFD_MOTION.refresh(); toast(I.tx('admin.saved')); return; }
    var l = e.target.closest('[data-deflang]');
    if (l) { setLang(l.getAttribute('data-deflang')); render(); toast(I.tx('admin.saved')); return; }
    if (e.target.closest('#copy')) {
      (navigator.clipboard ? navigator.clipboard.writeText(config()) : Promise.reject()).then(function () { toast(I.tx('admin.copied')); }, function () {
        var r = document.createRange(); r.selectNodeContents($('cfg')); var s = getSelection(); s.removeAllRanges(); s.addRange(r);
      });
    }
    if (e.target.closest('#dl')) {
      var a = document.createElement('a');
      a.href = URL.createObjectURL(new Blob([config()], { type: 'text/javascript' }));
      a.download = 'config.js'; document.body.appendChild(a); a.click(); a.remove();
      setTimeout(function () { URL.revokeObjectURL(a.href); }, 1000);
    }
    if (e.target.closest('#reset')) {
      TH.clear(); try { localStorage.removeItem(LANG_KEY); } catch (err) { /* ignore */ }
      render(); window.IFD_MOTION.refresh();
    }
  });

  (window.IFD_RENDERS = window.IFD_RENDERS || []).push(render);
})();
